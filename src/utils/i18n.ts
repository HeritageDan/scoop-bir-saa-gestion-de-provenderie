export function getTranslation(lang: Language, key: string): string {
  const dict = translations[lang] || translations.fr;
  if (dict[key]) return dict[key];
  if (translations.fr[key]) return translations.fr[key];

  // Try replacing '.' with '_'
  const keyWithUnder = key.replace(/\./g, '_');
  if (dict[keyWithUnder]) return dict[keyWithUnder];
  if (translations.fr[keyWithUnder]) return translations.fr[keyWithUnder];

  // Try replacing '_' with '.'
  const keyWithDots = key.replace(/_/g, '.');
  if (dict[keyWithDots]) return dict[keyWithDots];
  if (translations.fr[keyWithDots]) return translations.fr[keyWithDots];

  return key;
}
